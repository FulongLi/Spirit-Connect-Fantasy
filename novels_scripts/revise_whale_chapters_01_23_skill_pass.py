def md_to_html(text):
    out = []
    for line in text.splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("# "):
            out.append(f"<h1>{html.escape(s[2:])}</h1>")
        elif s.startswith("## "):
            out.append(f"<h2>{html.escape(s[3:])}</h2>")
        else:
            out.append(f"<p>{html.escape(s)}</p>")
    return "\n".join(out)


def page(title, body, nav):
    return f"""<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)}</title>
  <link rel="stylesheet" href="../assets/style.css">
</head>
<body><main>
{body}
{nav}
</main></body></html>
"""


def nav_for(stem):
    stems = [p.stem for p in sorted(ZH_MD.glob("*.md"))]
    idx = stems.index(stem)
    links = ['<nav class="chapter-nav">']
    if idx > 0:
        links.append(f'<a href="{html.escape(stems[idx - 1])}.html">上一章 / Previous</a>')
    links.append('<a href="../index.html">目录 / Index</a>')
    if idx < len(stems) - 1:
        links.append(f'<a href="{html.escape(stems[idx + 1])}.html">下一章 / Next</a>')
    links.append("</nav>")
    return "\n".join(links)


changed = []
for stem, replacements in REPLACEMENTS.items():
    path = ZH_MD / f"{stem}.md"
    text = path.read_text(encoding="utf-8")
    original = text
    missing = []
    for old, new in replacements.items():
        if old not in text:
            missing.append(old[:42])
        text = text.replace(old, new)
    if text != original:
        path.write_text(text, encoding="utf-8")
        (ZH_HTML / f"{stem}.html").write_text(
            page(stem, md_to_html(text), nav_for(stem)), encoding="utf-8"
        )
        changed.append(stem)
    if missing:
        print(f"[warn] {stem}: {len(missing)} replacement(s) not found")
        for item in missing:
            print(f"  - {item}")

print("Updated Chinese prose and HTML for:")
for stem in changed:
    print(f"- {stem}")
